#### Define Preparation Functions ####
# Data is "clean" in terms of data column accuracy. However, there is a need
# to construct identifier variables that support linking awards with publication
# and supplemental data used in analysis.

clean_awards_data <- function(df, consortium_name) {
  
  cat("\nCleaning", consortium_name, "awards data...\n")
  
  df_clean <- df %>%

    # Clean column names - use janitor to standardize
    clean_names() %>%
    
    # Standardize key identifiers
    dplyr::mutate(
      # Update data type for award serial numbers
      serial_number = as.character(serial_number),
      
      # Project Serial Number
      project_serial_number = paste0(ic,serial_number),
      
      # Core Project Number
      core_project_number = paste0(activity,ic,serial_number),
      
      # DUNS number
      duns_number = as.character(duns_number)
      
    ) %>%
    
    # Remove completely empty rows
    filter(!if_all(everything(), is.na)) %>%
    
    # Sort by fiscal year and project number
    arrange(project_number, fiscal_year)
  
  # Validation checks
  cat("  Checking for duplicate application IDs...\n")
  dupes <- df_clean %>%
    group_by(application_id) %>%
    filter(n() > 1) %>%
    ungroup()
  
  if (nrow(dupes) > 0) {
    warning("  Found ", nrow(dupes), " duplicate application IDs in ", 
            consortium_name, " data")
  }
  
  cat("  Cleaned", nrow(df_clean), "award records\n")
  
  return(df_clean)
}

#### Clean Each Consortium's Award Data ####
# Note, duplicate application identifiers may be accurate, as it may indicate
# shared funding streams within NIH ICs.

hubmap_awards_clean <- clean_awards_data(awards_list$HuBMAP, "HuBMAP")
sennet_awards_clean <- clean_awards_data(awards_list$SenNet, "SenNet")
htan_awards_clean <- clean_awards_data(awards_list$HTAN, "HTAN")

#### Supplement Awards Records with Consortium Division Metadata ####
# Add data to a list for adding Map Initiative metadata to award records.
df_list <- list(hubmap_awards_clean=hubmap_awards_clean, 
                sennet_awards_clean=sennet_awards_clean, 
                htan_awards_clean=htan_awards_clean)

# Process each data frame
df_list_updated <- map(df_list, function(df) {
  tmp <- df %>% 
    select(opportunity_number, project_serial_number) %>%
    filter(str_detect(opportunity_number, "RFA") | 
           str_detect(opportunity_number, "OTA")  ) %>%
    distinct()
  
  tmp <- left_join(tmp, award_metadata, 
                   by = "opportunity_number") %>%
    select(project_serial_number, division, division_type) %>%
    distinct()
  
  left_join(df, tmp,
            by = "project_serial_number",
            relationship = "many-to-many")
})

# Extract back to individual objects if needed
list2env(df_list_updated, envir = .GlobalEnv)

