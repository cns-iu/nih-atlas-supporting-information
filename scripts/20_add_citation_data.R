#### Environment Set-Up ####
source(here::here("scripts/00_setup.R"))

#### Load Data ####
# Load integrated publications
all_pubs <- 
  read.csv(file.path(project_root, "data", "processed",
           "NIHReporter-map_consortia-publications-distinct_pmid-validated.csv"),
           encoding = "UTF8")

# Load Citation data
# Web of Science data (wos_data)
wos_data <- 
  read.csv(file.path(project_root, "data", "citations",
                     "Web_of_Science-map_consoritia-pub_citations-20260211.csv"),
           encoding = "UTF8")

# Google Scholar (gs_data) data
gs_data <- 
  read.csv(file.path(project_root, "data", "citations",
                     "Google_Scholar-map_consortia-pub_citations-20260211.csv"),
           encoding = "UTF8")

#### Prepare Citation Data ####
wos_data <-
  wos_data %>%
  select(Pubmed.Id, Times.Cited..WoS.Core, Times.Cited..All.Databases)
names(wos_data) <- c("pmid", "times_cited_wos_core", "times_cited")
wos_data$citation_source <- "Web of Science"

gs_data <- 
  gs_data %>%
  select(pmid,gs_citation_ct) 
names(gs_data) <- c("pmid","times_cited")
gs_data$citation_source <- "Google Scholar"

# Bind citation data together
citations <- rbind(wos_data[,c(1,3,4)], gs_data)

#### Join citation data with publication data
all_pubs <- 
  left_join(all_pubs,citations, by="pmid") %>%
  distinct()

# Check linkage
n_with_citations <- sum(!is.na(all_pubs$times_cited))
linkage_rate <- round(n_with_citations / nrow(all_pubs) * 100, 1)

# Report on unmatched publication records
unmatched_records <- 
  all_pubs %>%
  filter(is.na(times_cited)) %>%
  select(pmid, title, pub_year, journal)

if (nrow(unmatched_records) > 0) {
  cat("  Unmatched publications:", nrow(unmatched_records), "\n")
  cat("  Saving list of unmatched publications for review...\n")
  write_csv(unmatched_records, 
            file.path(project_root, "outputs", "reports",
                      "publications_without_citations.csv"))
}


#### Save Outputs ####
cat("\nSaving outputs...\n")

# Save publications with citations
save_processed_data(all_pubs,
                    "NIHReporter-map_consortia-publications-validated-citations.csv")
