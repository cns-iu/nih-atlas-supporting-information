# Add cumulative year weights to edges
add_cumulative_pub_edge_weights <- 
  function(edges, pub_author_data, consortium_col) {
  message("  Adding cumulative year weights to edges...")
  
  # Filter publication data for this consortium
  consortium_pubs <- pub_author_data %>%
    filter(.data[[consortium_col]] >= 1) %>%
    filter(is_organization == FALSE)
  
  # Get unique years
  years <- sort(unique(consortium_pubs$year))
  
  # For each year, calculate cumulative co-authorship counts
  for (yr in years) {
    # Filter to publications up to and including this year
    pub_author_subset <- consortium_pubs %>% filter(year <= yr)
    
    # Create temporary incidence matrix
    pubs_temp <- pub_author_subset %>%
      select(record_id, disambiguated_name)
    names(pubs_temp) <- c("pmid", "author")
    
    pub_list <- unique(pubs_temp$pmid)
    author_list <- unique(pubs_temp$author)
    
    pub_idx <- match(pubs_temp$pmid, pub_list)
    author_idx <- match(pubs_temp$author, author_list)
    
    inc_temp <- sparseMatrix(
      i = pub_idx,
      j = author_idx,
      x = 1,
      dims = c(length(pub_list), length(author_list)),
      dimnames = list(pub_list, author_list)
    )
    
    coauth_temp <- calculate_coauthorship(inc_temp)
    
    # Extract weights for existing edges
    edge_weights <- numeric(nrow(edges))
    for (i in seq_len(nrow(edges))) {
      author1 <- edges$to[i]
      author2 <- edges$from[i]
      
      # Check if both authors exist in this year's matrix
      if (author1 %in% rownames(coauth_temp) && author2 %in% rownames(coauth_temp)) {
        edge_weights[i] <- coauth_temp[author1, author2]
      } else {
        edge_weights[i] <- 0
      }
    }
    
    # Add column for this year
    col_name <- paste0("weight_", yr)
    edges[[col_name]] <- edge_weights
    
    message(sprintf("    Added weights for year %d", yr))
  }
  
  return(edges)
}

# Add publication metrics to nodes
add_cumulative_pub_node_weights <- 
  function(nodes, pub_author_data, consortium_col) {
  message("  Adding publication metrics to nodes...")
  
  # Filter to this consortium
  consortium_pubs <- 
    pub_author_data %>%
    filter(.data[[consortium_col]] >= 1) %>%
    filter(is_organization == FALSE) %>%
    as.data.table()
  
  # Calculate first publication year
  first_year <- consortium_pubs[, .(first_publication_year = min(year, na.rm = TRUE)),
                                by = disambiguated_name]
  nodes <- merge(nodes, first_year, by.x = "id", by.y = "disambiguated_name", all.x = TRUE)
  
  # Calculate total publication count
  total_pubs <- 
    consortium_pubs[, .(publications = .N), 
                    by = disambiguated_name]
  nodes <- 
    merge(nodes, total_pubs, 
          by.x = "id", 
          by.y = "disambiguated_name", all.x = TRUE)
  
  # Calculate cumulative publications by year
  years <- sort(unique(consortium_pubs$year))
  for (yr in years) {
    pubs_to_year <- consortium_pubs[year <= yr, .N, by = disambiguated_name]
    setnames(pubs_to_year, "N", paste0("pubs_", yr))
    nodes <- merge(nodes, pubs_to_year, by.x = "id", by.y = "disambiguated_name", all.x = TRUE)
    
    # Fill NA with 0
    col_name <- paste0("pubs_", yr)
    nodes[[col_name]][is.na(nodes[[col_name]])] <- 0
    
    message(sprintf("    Added publication counts for year %d", yr))
  }
  
  return(nodes)
}

# Add citation metrics to nodes
add_citation_node_counts <- 
  function(nodes, pub_author_data, consortium_col) {
  message("  Adding citation counts to nodes...")
  
  # Filter to this consortium
  consortium_pubs <- 
    pub_author_data %>%
    filter(.data[[consortium_col]] >= 1) %>%
    filter(is_organization == FALSE)
  
  # Join citations and author counts to consortium publications
  author_cites <- 
    consortium_pubs %>%
    mutate(
      times_cited = replace_na(times_cited, 0),
      author_count = replace_na(author_count, 1),
      weighted_citations = round(times_cited / author_count, digits=2)
    )
  
  # Sum citations per author (both raw and weighted)
  total_cites <- 
    author_cites %>%
    group_by(disambiguated_name) %>%
    summarise(
      citations = sum(times_cited, na.rm = TRUE),
      weighted_citations = sum(weighted_citations, na.rm = TRUE),
      .groups = "drop"
    )
  
  # Join to nodes
  nodes <- nodes %>%
    left_join(total_cites, by = c("id" = "disambiguated_name")) %>%
    mutate(
      citations = replace_na(citations, 0),
      weighted_citations = replace_na(weighted_citations, 0)
    )
  
  message(sprintf("    Added citation counts for %d authors", nrow(nodes)))
  
  return(nodes)
}

# Add division publication counts to nodes, overall and internal collaborations;
# Add home division(s) associated with a researcher.

add_division_metrics <- 
  function(nodes, pub_author_data, consortium_col, award_metadata) {
  message("  Adding division counts to nodes...")
  
  # Common consortia ID
  consortia_id <- str_replace(consortium_col, 
                              pattern = "_index",
                              replacement="")
  
  # Get division columns for this consortium from metadata
  consortium_divisions <- 
    award_metadata %>%
    filter(project_id == 
             consortium_col %>%
             str_replace(pattern="_index",
                         replacement="")) %>%
    pull(division)
  
  if (length(consortium_divisions) == 0) {
    message("No divisions found in metadata for this consortium")
    return(nodes)
  }
  
  # Filter to this consortium, excluding organizations
  consortium_pubs <- 
    pub_author_data %>%
    filter(.data[[consortium_col]] >= 1) %>%
    select(-.data[[consortium_col]],
           -paste0(consortia_id,"_divisions"),
           -paste0(consortia_id,"_projects")
           ) %>%
    filter(is_organization == FALSE)
  
  # Subset to partition for publications documenting consortia research collaboration 
  consortium_collab_pubs <-
    consortium_pubs %>% 
    filter(consortia_collaboration == 1)
  
  # Sum division publications per author
  division_summary <- 
    consortium_pubs %>%
    group_by(disambiguated_name) %>%
    summarise(across(all_of(consortium_divisions), ~sum(., na.rm = TRUE)), 
              .groups = "drop")
  
  # Sum division consortia collaboration publications per author
  division_collab_summary <- 
    consortium_collab_pubs %>% 
    group_by(disambiguated_name) %>%
    summarise(across(all_of(consortium_divisions), ~sum(., na.rm = TRUE)), 
              .groups = "drop") %>%
    rename_with(~ paste0(.x,"_internal_collabs", recycle0 = TRUE)) %>%
    rename("disambiguated_name" = "disambiguated_name_internal_collabs")
  
  # Join to nodes
  nodes <- 
    nodes %>%
    left_join(division_summary, by = c("id" = "disambiguated_name")) %>%
    left_join(division_collab_summary, by = c("id" = "disambiguated_name"))
  
  # Fill NAs with 0
  nodes <- 
    nodes %>%
  
  return(nodes)
}

# Add PI role flag to nodes
add_pi_role <- function(nodes, award_pi_data, consortium_col) {
  message("  Adding PI role flags to nodes...")
  
  # Get unique PI names from award data
  pi_names <- 
    award_pi_data %>%
    filter(.data[[consortium_col]] == 1) %>%
    pull(disambiguated_name) %>%
    unique() 
  
  # Add role column
  nodes$role <- ifelse(nodes$id %in% pi_names, "Principal Investigator", "Researcher")
  
  pi_count <- sum(nodes$role == "Principal Investigator")
  message(sprintf("    Identified %d principal investigators", pi_count))
  
  return(nodes)
}
