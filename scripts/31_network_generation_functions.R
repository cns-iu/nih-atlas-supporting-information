##### Bi-modal incidence matrix #####
# Function: Create bi-modal incidence matrix from publication-author data by consortia
create_consortia_incidence_matrix <- 
  function(pub_author_data, consortium_col) {
  # Create sparse matrix: rows = publications, columns = authors
  # Get unique publications and authors pairs
  pubs <- 
    pub_author_data %>%
    filter(.data[[consortium_col]]>=1) %>%
    filter(is_organization==FALSE) %>%
    select(record_id, disambiguated_name)
  names(pubs) <- c("pmid","author")
  
  pub_list <- unique(pubs$pmid)
  author_list <- unique(pubs$author)
  
  # Create factor indices
  pub_idx <- match(pubs$pmid, pub_list)
  author_idx <- match(pubs$author, author_list)
  
  # Create sparse matrix
  incidence_matrix <- 
    sparseMatrix(
    i = pub_idx,
    j = author_idx,
    x = 1,
    dims = c(length(pub_list), length(author_list)),
    dimnames = list(pub_list, author_list)
  )
  
  # Clean up environment
  rm(pub_idx,author_idx,author_list,pub_list,pubs)
  
  return(incidence_matrix)
}

##### Co-authorship network matrix via transposition #####
# Function: Calculate co-authorship matrix via transposition
calculate_coauthorship <- 
  function(incidence_matrix) {
  # Multiply transpose by original to get co-authorship
  # Result is symmetric matrix: authors × authors
  coauth_matrix <- t(incidence_matrix) %*% incidence_matrix
  
  # Set diagonal to 0 (remove self-loops)
  diag(coauth_matrix) <- 0
  
  return(coauth_matrix)
}

##### Co-authorship network matrix to igraph #####
# Function: Convert co-authorship matrix to igraph object
matrix_to_igraph <- function(coauth_matrix) {
  # Create graph from adjacency matrix
  # Mode = "undirected" since co-authorship is symmetric
  # Weighted = TRUE to preserve edge weights
  graph <- graph_from_adjacency_matrix(
    coauth_matrix,
    mode = "undirected",
    weighted = TRUE,
    diag = FALSE
  )
  
  return(graph)
}

