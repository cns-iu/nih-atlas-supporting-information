# Function: Extract edge list from igraph object
extract_edge_list <- function(graph) {
  # Get edge list
  el <- as_edgelist(graph, names = TRUE)
  
  # Create data table
  edges <- data.table(
    from = el[, 1],
    to = el[, 2],
    source = el[, 1],
    target = el[, 2],
    weight = E(graph)$weight
  )
  
  return(edges)
}

# Function: Extract node list from igraph object
extract_node_list <- function(graph) {
  # Get vertex names
  nodes <- data.table(
    id = V(graph)$name,
    label = V(graph)$name
  )
  
  return(nodes)
}

# Function: normalize_edges
# Normalizes edge pairs by ensuring the smaller ID is always the source
# This makes (A,B) and (B,A) identical for comparison purposes
#
# Args:
#   edge_df: data frame with 'source' and 'target' columns
#
# Returns:
#   data frame with normalized 'source' and 'target' columns, plus a 
#   'normalized_edge' column for explicit joining

normalize_edges <- function(edge_df) {
  edge_df %>%
    mutate(
      # Create normalized pairs where smaller ID is always first
      source_norm = pmin(source, target),
      target_norm = pmax(source, target),
      # Create a composite key for joining
      normalized_edge = paste0(source_norm, "_", target_norm)
    ) %>%
    select(-source, -target) %>%
    rename(source = source_norm, target = target_norm)
}

# Function: join_undirected_edges
# Joins edge lists from baseline and partition networks with full data retention
#
# Args:
#   baseline_edges: data frame with 'source' and 'target' columns (and optional attributes)
#   partition_edges: data frame with 'source' and 'target' columns (and optional attributes)
#   by_suffix: suffixes for columns from baseline and partition (default: c(".baseline", ".partition"))
#   join_type: "inner", "left", "right", or "full" (default: "full")
#
# Returns:
#   Joined edge list with:
#   - source, target: normalized edge pairs
#   - normalized_edge: composite key used for joining
#   - All other columns from both data frames (with suffixes applied to duplicates)
#   - match_type: indicator of where edge came from (in both, only in baseline, etc.)

join_undirected_edges <- 
  function(baseline_edges,
           partition_edges,
           by_suffix = c(".baseline", ".partition"),
           join_type = "full") {
  
  # Validate inputs
  if (!("source" %in% names(baseline_edges) && "target" %in% names(baseline_edges))) {
    stop("baseline_edges must contain 'source' and 'target' columns")
  }
  
  if (!("source" %in% names(partition_edges) && "target" %in% names(partition_edges))) {
    stop("partition_edges must contain 'source' and 'target' columns")
  }
  
  if (!(join_type %in% c("inner", "left", "right", "full"))) {
    stop("join_type must be one of: 'inner', 'left', 'right', 'full'")
  }
  
  # Normalize edges in both data frames
  baseline_norm <- normalize_edges(baseline_edges)
  partition_norm <- normalize_edges(partition_edges)
  
  # Perform the join based on type
  if (join_type == "inner") {
    joined <- inner_join(baseline_norm, partition_norm, 
                         by = "normalized_edge",
                         suffix = by_suffix)
  } else if (join_type == "left") {
    joined <- left_join(baseline_norm, partition_norm, 
                        by = "normalized_edge",
                        suffix = by_suffix)
  } else if (join_type == "right") {
    joined <- right_join(baseline_norm, partition_norm, 
                         by = "normalized_edge",
                         suffix = by_suffix)
  } else { # full
    joined <- full_join(baseline_norm, partition_norm, 
                        by = "normalized_edge",
                        suffix = by_suffix)
  }
  
  # Handle source/target columns from both data frames
  # After full_join, we may have source.x, target.x, source.y, target.y
  # We need to consolidate these into single source/target columns
  
  if ("source.x" %in% names(joined)) {
    joined <- joined %>%
      mutate(
        source = coalesce(source.x, source.y),
        target = coalesce(target.x, target.y),
        .keep = "unused"
      )
  }
  
  # Add match_type indicator
  baseline_cols <- setdiff(names(baseline_norm), c("source", "target", "normalized_edge"))
  partition_cols <- setdiff(names(partition_norm), c("source", "target", "normalized_edge"))
  
  joined <- joined %>%
    mutate(
      in_baseline = !is.na(if_any(any_of(baseline_cols), ~ !is.na(.))) | 
                    (is.na(if_any(any_of(partition_cols), ~ !is.na(.)))),
      in_partition = !is.na(if_any(any_of(partition_cols), ~ !is.na(.))),
      match_type = case_when(
        in_baseline & in_partition ~ "both",
        in_baseline & !in_partition ~ "baseline_only",
        !in_baseline & in_partition ~ "partition_only",
        TRUE ~ NA_character_),
    .keep = "unused"
    )

# Reorder columns: source, target, match_type, normalized_edge, then others
core_cols <- c("source", "target", "match_type", "normalized_edge")
other_cols <- setdiff(names(joined), core_cols)

joined %>%
  select(all_of(core_cols), all_of(other_cols))
}

