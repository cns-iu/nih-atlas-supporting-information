# ==============================================================================
# Script 31: Generate Co-authorship Networks
# ==============================================================================
# Purpose: Generate co-authorship networks for each atlas initiative using
#          matrix transposition approach. Creates node and edge lists with
#          cumulative annual metrics for publications and citations.
#
# Inputs:
#   - data/name_disambiguation/NIH-map_consortia-names_for_disambiguation-results.csv
#   - data/metadata/NIH-map_consortium_awards-division-metadata.csv
#   - data/processed/NIHReporter-map_consortia-publications-validated-citations.csv"
#
# Outputs:
#   - data/metadata/NIH-map-publication_coauthor_network_partition_indices.csv
#   - data/networks/{consortium}-coauthorship-baseline-nodes.csv
#   - data/networks/{consortium}-coauthorship-baseline-edges.csv
#   - data/networks/{consortium}-coauthorship-collaboration_partition-edges.csv
#   - data/networks/{consortium}-coauthorship-collaboration_partition-nodes.csv
#
# Author: Michael Ginda
# Note: Initial script generated by Claude Sonnet 4.5 LLM.
# Initial Commit: 2026-02-17
# Last Update: 2026-05-28
# ==============================================================================

#### Set up Environment ####
# Load required libraries
library(Matrix)

# Source setup functions
source(here::here("scripts/00_setup.R"))
source(here::here("scripts/30_network_generation_functions.R"))

#### Load Data ####
message("Loading data...")

# Load disambiguated names data (contains all required information)
names_data <- 
  read.csv(file.path(project_root, dirs[6],
                     "NIH-map_consortia-names_for_disambiguation-revised_field_set-results.csv"),
                       header = T, encoding = "UTF8")

# Load publications data
publications_data <- 
  read.csv(file.path(project_root,dirs[4],
                     "NIHReporter-map_consortia-publications-validated-citations.csv"),
           header = T, encoding = "UTF8",
           colClasses = c("pmid"="character", "pmc_id"="character")
  )

# Load atlas consortia opportunity and division metadata
award_metadata <- 
  read.csv(file=file.path(project_root,dirs[2],
                          "NIH-map_consortia_awards-division-metadata.csv"),
           header=T)

#### Create Network Data Sets and Partitions ####
# Subset name data sets by source
pub_author_data <- 
  names_data %>%
  filter(source=="publications") %>%
  select(-source)
    
# Subset of data that involves a consortia internal collaboration
pub_author_collab_data <- 
  pub_author_data %>%
  filter(consortia_collaboration==1)

# Award PI data set
award_pi_data <- 
  names_data %>%
  filter(source=="awards") %>%
  select(record_id,year,original_name,disambiguated_name,role,is_organization,
         ends_with("_index"))
rm(names_data)

#### Consortia metadata ####
# Atlas consortia indices
consortium_cols <- names(pub_author_data)[names(pub_author_data) %in% 
                                            c("HuBMAP_index", "SenNet_index", "HTAN_index")]

# Set Atlas consortia research division metadata
award_metadata <- 
  award_metadata %>%
  select(project_id, division) %>%
  distinct() %>%
  mutate(division = tolower(division))

#### Consortia and Network Publication Indices ####
# Baseline networks 
baseline_index <- 
  pub_author_data %>%
  filter(is_organization==FALSE) %>%
  select(record_id) %>%
  mutate(baseline_network = 1) %>% 
  rename("pmid" = "record_id") %>%
  distinct()

# Consortia collaboration publication network partitions.
consortial_collaboration_index <-
  pub_author_collab_data %>%
  filter(is_organization==FALSE) %>%
  select(record_id) %>%
  mutate(consortia_collab_partition = 1) %>%
  rename("pmid" = "record_id") %>%
  distinct()

# Create index of publications used in networks
publication_network_indices <- 
  publications_data %>%
  select(pmid, pub_year, is_preprint, preprint_matched, multiatlas, 
         HTAN_index, SenNet_index, HuBMAP_index, division_collaboration) %>%
  left_join(baseline_index, by="pmid") %>%
  left_join(consortial_collaboration_index, by="pmid") %>%
  mutate(consortia_collab_partition = replace_na(consortia_collab_partition, 0)) %>%
  distinct()

write.csv(publication_network_indices, 
          file="data/metadata/NIH-map-publication_coauthor_network_partition_indices.csv",
          row.names = FALSE)

rm(publications_data, baseline_index, consortial_collaboration_index)

#### Process Consortia Baseline Co-authorship Networks ####
##### Process Each Consortium ####
for(consortium in consortium_cols) {
  consortia_id <- str_replace(consortium,"_index","")
  
  message("\n", paste(rep("=", 80), collapse = ""))
  message(sprintf("Processing %s Co-authorship Network", consortia_id))
  message(paste(rep("=", 80), collapse = ""))
  
  # Create incidence matrix and co-authorship network
  message("  Creating baseline networks...")
  inc_matrix <- create_consortia_incidence_matrix(pub_author_data, consortium)
  coauth_matrix <- calculate_coauthorship(inc_matrix)
  coauth_graph <- matrix_to_igraph(coauth_matrix)
  
  # Extract and enhance edge list
  message("  Processing edges...")
  edges <- extract_edge_list(coauth_graph)
  edges <- add_cumulative_pub_edge_weights(edges, pub_author_data, consortium)
  
  # Normalize Edge Source/Target values
  edges <- normalize_edges(edges)
  edges$from <- edges$source
  edges$to <- edges$target
  edges <- 
    edges %>% 
    select(normalized_edge, from, to, source, target, starts_with("weight"))
  
  # Extract and enhance node list
  message("  Processing nodes...")
  nodes <- extract_node_list(coauth_graph)
  nodes <- add_cumulative_pub_node_weights(nodes, pub_author_data, consortium)
  nodes <- add_citation_node_counts(nodes, pub_author_data, consortium)
  nodes <- add_pi_role(nodes, award_pi_data, consortium)
  nodes <- add_division_metrics(nodes, pub_author_data, consortium, award_metadata)
  
  # Update values with NA induced in node list.
  nodes <-
    nodes %>%
    mutate(across(everything(), ~replace_na(., 0)))
  
  # Save outputs
  message("  Saving files...")
  if (!dir.exists("data/networks")) {
    dir.create("data/networks", recursive = TRUE)
  }
  
  edges_file <- 
    sprintf("data/networks/%s-coauthorship-baseline-edges.csv", consortia_id)
  nodes_file <- 
    sprintf("data/networks/%s-coauthorship-baseline-nodes.csv", consortia_id)
  
  fwrite(edges, edges_file)
  fwrite(nodes, nodes_file)
  
  message(sprintf("    Saved: %s", edges_file))
  message(sprintf("    Saved: %s", nodes_file))
  
  # Print summary
  message(sprintf("\n  Network Summary:"))
  message(sprintf("    Nodes: %d", nrow(nodes)))
  message(sprintf("    Edges: %d", nrow(edges)))
  message(sprintf("    PIs: %d", sum(nodes$role == "Principal Investigator")))
  message(sprintf("    Researchers: %d", sum(nodes$role == "Researcher")))
}

#### Process Internal Collaboration Partition Co-authorship Network ####
##### Process Each Consortium ####
for(consortium in consortium_cols) {
  # Consortia identifier
  consortia_id <- str_replace(consortium,"_index","")
 
  message("\n", paste(rep("=", 80), collapse = ""))
  message(sprintf("Processing %s Co-authorship Network Partition", consortia_id))
  message(paste(rep("=", 80), collapse = ""))
  
  # Identify consortia collaboration type associated with a publication
  pub_author_collab_type <- 
    pub_author_collab_data %>%
    filter(.data[[consortium]]==1) %>%
    filter(is_organization==FALSE) %>%
    select(record_id, disambiguated_name,
           starts_with(consortia_id)) %>%
    mutate("collaboration_type" = c("single_project")) %>%
    distinct()
  names(pub_author_collab_type)[2:5] <- c("id","index","divisions","projects")
  
  # Identify intradivision collaboration papers
  if(nrow(pub_author_collab_type[
            pub_author_collab_type$divisions == 1 &
            pub_author_collab_type$projects >= 2, ])>0){
     pub_author_collab_type[
         pub_author_collab_type$divisions == 1 &
         pub_author_collab_type$projects > 1,]$collaboration_type <-
      "intradivision_collaboration"
  }
  
  # Identify interdivision collaboration papers
  if(nrow(pub_author_collab_type[
              pub_author_collab_type$divisions > 1 &
              pub_author_collab_type$projects >= 2, ])>0){
     pub_author_collab_type[
         pub_author_collab_type$divisions > 1 &
         pub_author_collab_type$projects > 1, ]$collaboration_type <-
    "interdivision_collaboration"
  }
  
  # Filter publication consortia collaboration type data
  pub_author_collab_type <-
    pub_author_collab_type %>% 
    filter(collaboration_type != "single_project") %>%
    select(record_id, id, collaboration_type) %>% 
    mutate(collaboration_type = 
             factor(collaboration_type, 
                    levels=c("interdivision_collaboration",
                             "intradivision_collaboration")))
  
  # Identify set of collaboration PMID that remain after filtering
  pub_author_collab_pmid <- unique(pub_author_collab_type$record_id)
  
  # Calculate node weights for interdivision and intradivision collaborations
  pub_author_collab_type <-
    pub_author_collab_type %>%
    pivot_wider(id_cols=id, names_from=collaboration_type,
                names_expand = TRUE,
                values_from = record_id, values_fn = length,
                values_fill = 0)
  
  # Ensure pub_author_collab_data subset has accurate set of PMID 
  # Removes and pubs where consortia of interest has single project collaboration
  # type classification where the publications includes an external collaboration
  # with another atlas consortia in the study.
  consortia_collab_data <- 
    pub_author_collab_data[pub_author_collab_data$record_id %in% 
                             pub_author_collab_pmid,]
  
  # Create incidence matrix and co-authorship network
  message("  Creating partitioned networks...")
  inc_matrix <- 
    create_consortia_incidence_matrix(consortia_collab_data, consortium)
  coauth_matrix <- 
    calculate_coauthorship(inc_matrix)
  coauth_graph <- 
    matrix_to_igraph(coauth_matrix)
  
  # Extract and enhance edge list
  message("  Processing edges...")
  edges <- extract_edge_list(coauth_graph)
  edges <- 
    add_cumulative_pub_edge_weights(edges, consortia_collab_data, consortium)
  
  # Normalize Edge Source/Target value order
  edges <- normalize_edges(edges)
  edges$from <- edges$source
  edges$to <- edges$target
  edges <- edges %>% 
    select(normalized_edge, from, to, source, target, starts_with("weight"))
  
  # Update edge list names - weights
  names(edges) <- sub("weight","ic_weight", names(edges))

  # Extract and enhance node list
  message("  Processing nodes...")
  nodes <- extract_node_list(coauth_graph)
  nodes <- 
    nodes %>%
    left_join(pub_author_collab_type, by="id")
  nodes <- add_cumulative_pub_node_weights(nodes, consortia_collab_data, consortium)
  nodes <- add_citation_node_counts(nodes, consortia_collab_data, consortium)
  nodes <- add_pi_role(nodes, award_pi_data, consortium)
   
  # Update node list names - weights
  names(nodes) <- sub("pubs","cc_pubs", names(nodes))
  
  # reorder columns for network
  nodes <-
    nodes %>%
    select(id, role, publications,
           interdivision_collaboration,intradivision_collaboration,
           starts_with("cc_pubs"), citations, weighted_citations) %>%
    rename("ic_publications" = "publications",
           "ic_citations" = "citations", 
           "ic_weighted_citations" = "weighted_citations")
  
  # Update values with NA induced in node list.
  nodes <-
    nodes %>%
    mutate(across(everything(), ~replace_na(., 0)))
  
  # Save outputs
  message("  Saving files...")
  if (!dir.exists("data/networks")) {
    dir.create("data/networks", recursive = TRUE)
  }
  
  edges_file <- 
    sprintf("data/networks/%s-coauthorship-collaboration_partition-edges.csv", consortia_id)
  nodes_file <- 
    sprintf("data/networks/%s-coauthorship-collaboration_partition-nodes.csv", consortia_id)
  
  fwrite(edges, edges_file)
  fwrite(nodes, nodes_file)
  
  message(sprintf("    Saved: %s", edges_file))
  message(sprintf("    Saved: %s", nodes_file))
  
  # Print summary
  message(sprintf("\n  Network Summary:"))
  message(sprintf("    Nodes: %d", nrow(nodes)))
  message(sprintf("    Edges: %d", nrow(edges)))
}
