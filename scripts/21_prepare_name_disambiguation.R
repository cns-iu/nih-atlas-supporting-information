# Detect if a name is likely an organization
is_organization <- function(name) {
  if (is.na(name) || name == "") {
    return(FALSE)
  }
  
  # Common patterns indicating organizations
  org_patterns <- c(
    "\\bConsortium\\b",
    "\\bGroup\\b",
    "\\bTeam\\b",
    "\\bCenter\\b",
    "\\bCentre\\b",
    "\\bInstitute\\b",
    "\\bUniversity\\b",
    "\\bCollege\\b",
    "\\bDepartment\\b",
    "\\bDivision\\b",
    "\\bLaboratory\\b",
    "\\bFoundation\\b",
    "\\bSociety\\b",
    "\\bAssociation\\b",
    "\\bNetwork\\b",
    "\\bCollaboration\\b",
    "\\bInvestigators\\b",
    "\\bCooperative\\b",
    "\\bProgram\\b",
    "\\bStudy\\b"
  )
  
  # Check if any pattern matches (case insensitive)
  any(str_detect(name, regex(org_patterns, ignore_case = TRUE)))
}

# Parse semicolon-separated names into individual records
parse_names <- function(names_string) {
  if (is.na(names_string) || names_string == "" || names_string == "Not Applicable") {
    return(character(0))
  }
  
  # Split by semicolon and trim whitespace
  names <- str_trim(unlist(str_split(names_string, ";")))
  
  # Remove empty strings
  names <- names[names != "" & names != "Not Applicable"]
  
  return(names)
}

