# Create list to store PI records
pi_records <- list()

for (i in 1:nrow(awards)) {
  row <- awards[i, ]

  # Get both PI fields
  contact_pi <- row$contact_pi_project_leader
  other_pis <- row$other_pi_or_project_leader_s
  
  # Combine all PIs for this award
  all_pis <- character(0)
  
  # Add contact PI if present
  if (!is.na(contact_pi) && contact_pi != "" && contact_pi != "Not Applicable") {
    all_pis <- c(all_pis, contact_pi)
  }
  
  # Add other PIs if present
  if (!is.na(other_pis) && other_pis != "" && other_pis != "Not Applicable") {
    other_pi_list <- parse_names(other_pis)
    all_pis <- c(all_pis, other_pi_list)
  }
  
  # Create a record for each PI
  if (length(all_pis) > 0) {
    for (pi_name in all_pis) {
      pi_records[[length(pi_records) + 1]] <- data.table(
        source = "awards",
        record_id = row$core_project_number,
        year = row$fiscal_year,
        original_name = pi_name,
        disambiguated_name = str_to_title(pi_name),
        role = "Principal Investigator",
        is_organization = is_organization(pi_name),
        author_count = NA,
        times_cited = NA,
        consortia_collaboration = NA,
        multi_atlas = NA,
        HTAN_index = ifelse(row$project_id == "HTAN",1,0),
